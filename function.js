"use strict";
const addTowNumbers = (num1, num2) => {
    const totalSum = num1 + num2;
    return [totalSum];
};
const substructTowNumbers = (num1, num2) => {
    const total = num1 - num2;
    return [total];
};
const multiplayTowNumbers = (num1, num2) => {
    const total = num1 * num2;
    return [total];
};
